static inline uint32_t vn_compose_mark(uint32_t base, uint32_t mark) {
    int idx = -1;
    switch (mark) {
        case 0x0300: idx = 0; break;
        case 0x0301: idx = 1; break;
        case 0x0302: idx = 2; break;
        case 0x0303: idx = 3; break;
        case 0x0306: idx = 4; break;
        case 0x0309: idx = 5; break;
        case 0x031B: idx = 6; break;
        case 0x0323: idx = 7; break;
        default: return 0;
    }
    if (base > 0x1fff) return 0;
    uint16_t key = (uint16_t)((base << 3) | (uint32_t)idx);
    int low = 0, high = (int)(sizeof(k_vn_comb_table) / sizeof(k_vn_comb_table[0])) - 1;
    while (low <= high) {
        int mid = (low + high) / 2;
        if (k_vn_comb_table[mid].key == key) return k_vn_comb_table[mid].composed;
        if (k_vn_comb_table[mid].key < key) low = mid + 1;
        else high = mid - 1;
    }
    return 0;
}

static inline size_t vn_utf8_encode(uint32_t cp, char* out) {
    if (cp < 0x80) {
        out[0] = (char)cp;
        return 1;
    }
    if (cp < 0x800) {
        out[0] = (char)(0xC0 | (cp >> 6));
        out[1] = (char)(0x80 | (cp & 0x3F));
        return 2;
    }
    if (cp < 0x10000) {
        out[0] = (char)(0xE0 | (cp >> 12));
        out[1] = (char)(0x80 | ((cp >> 6) & 0x3F));
        out[2] = (char)(0x80 | (cp & 0x3F));
        return 3;
    }
    out[0] = (char)(0xF0 | (cp >> 18));
    out[1] = (char)(0x80 | ((cp >> 12) & 0x3F));
    out[2] = (char)(0x80 | ((cp >> 6) & 0x3F));
    out[3] = (char)(0x80 | (cp & 0x3F));
    return 4;
}

static inline size_t vn_normalize_utf8_inplace(char* str, size_t len) {
    if (!str || !len) return 0;
    const char* src = str;
    const char* end = str + len;
    char* dst = str;
    while (src < end) {
        uint8_t b0 = (uint8_t)*src;
        if (b0 == 0) break;
        uint32_t cp = 0;
        if (b0 < 0x80) {
            cp = b0;
            src += 1;
        } else if ((b0 & 0xE0) == 0xC0 && src + 1 < end && ((uint8_t)src[1] & 0xC0) == 0x80) {
            cp = ((uint32_t)(b0 & 0x1F) << 6) | ((uint8_t)src[1] & 0x3F);
            src += 2;
        } else if ((b0 & 0xF0) == 0xE0 && src + 2 < end && ((uint8_t)src[1] & 0xC0) == 0x80 && ((uint8_t)src[2] & 0xC0) == 0x80) {
            cp = ((uint32_t)(b0 & 0x0F) << 12) | ((uint32_t)((uint8_t)src[1] & 0x3F) << 6) | ((uint8_t)src[2] & 0x3F);
            src += 3;
        } else if ((b0 & 0xF8) == 0xF0 && src + 3 < end && ((uint8_t)src[1] & 0xC0) == 0x80 && ((uint8_t)src[2] & 0xC0) == 0x80 && ((uint8_t)src[3] & 0xC0) == 0x80) {
            cp = ((uint32_t)(b0 & 0x07) << 18) | ((uint32_t)((uint8_t)src[1] & 0x3F) << 12) | ((uint32_t)((uint8_t)src[2] & 0x3F) << 6) | ((uint8_t)src[3] & 0x3F);
            src += 4;
        } else {
            *dst++ = *src++;
            continue;
        }

        while (src < end) {
            uint8_t nb0 = (uint8_t)src[0];
            if (nb0 != 0xCC && nb0 != 0xCD) break;
            if (src + 1 >= end || ((uint8_t)src[1] & 0xC0) != 0x80) break;
            uint32_t mark = ((uint32_t)(nb0 & 0x1F) << 6) | ((uint8_t)src[1] & 0x3F);
            uint32_t composed = vn_compose_mark(cp, mark);
            if (composed == 0) break;
            cp = composed;
            src += 2;
        }

        dst += vn_utf8_encode(cp, dst);
    }
    *dst = '\0';
    return (size_t)(dst - str);
}

