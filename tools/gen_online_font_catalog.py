"""Generate the offline font allowlist from verified author metadata; no networking."""
import argparse
import json
from pathlib import Path
import re
from urllib.parse import urlsplit

ROOT=Path(__file__).resolve().parents[1]

def generate(data):
    if len(data)!=5:raise ValueError('Expected five curated fonts')
    lines=['/* Generated by tools/gen_online_font_catalog.py; keep original OFL notices. */']
    names=set()
    for i,item in enumerate(data):
        uri=urlsplit(item['url'])
        if uri.scheme!='https' or uri.hostname not in {'github.com','raw.githubusercontent.com'} or uri.username or uri.password:
            raise ValueError('Unapproved author source')
        filename=item['filename']
        if not re.fullmatch(r'kiiko-[a-z0-9-]+\.ttf',filename) or len(filename)>90 or filename in names:
            raise ValueError('Invalid managed filename')
        names.add(filename)
        if not 1024<item['size']<=32*1024*1024 or not 1024<item['source_size']<=32*1024*1024:
            raise ValueError('Unbounded font')
        if not re.fullmatch('[0-9a-f]{64}',item['sha256']) or not re.fullmatch('[0-9a-f]{64}',item['source_sha256']):
            raise ValueError('Missing SHA256')
        if item['deflate_offset']+item['deflate_size']>item['source_size'] or item['deflate_offset']<0 or item['deflate_size']<0:
            raise ValueError('Invalid pinned ZIP payload')
        if 'SIL OPEN FONT LICENSE Version 1.1' not in item['license'] or 'Copyright' not in item['license']:
            raise ValueError('Missing original OFL notice')
        lines.append('static const char font_license_%d[] = %s;'%(i,json.dumps(item['license'],ensure_ascii=False)))
    lines.append('static const online_font_item_t s_fonts[ONLINE_FONT_COUNT] = {')
    for i,item in enumerate(data):
        lines.append('    {')
        for field,key in [('name','name'),('ascii_name','ascii'),('filename','filename'),('url','url')]:
            lines.append('        .%s=%s,'%(field,json.dumps(item[key],ensure_ascii=False)))
        lines.append('        .license=font_license_%d,'%i)
        for field in ('size','source_size','deflate_offset','deflate_size'):
            lines.append('        .%s=%du,'%(field,item[field]))
        for field in ('sha256','source_sha256'):
            lines.append('        .%s={%s},'%(field,','.join('0x'+item[field][j:j+2] for j in range(0,64,2))))
        lines.append('    },')
    lines.append('};')
    return '\n'.join(lines)+'\n'

def generate_names(data):
    lines=['/* Generated font labels; no face data or network dependency. */','#pragma once',
           '#include <string.h>','static inline const char *online_font_catalog_name(const char *stem) {']
    for item in data:
        lines.append('    if (!strcmp(stem,%s)) return %s;'%(json.dumps(item['filename'][:-4]),json.dumps(item['name'],ensure_ascii=False)))
    return '\n'.join(lines+['    return NULL;','}'])+'\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog',type=Path,default=ROOT/'main/font/online_fonts.json')
    parser.add_argument('--output',type=Path,default=ROOT/'main/font/online_font_catalog.inc')
    args=parser.parse_args()
    data=json.loads(args.catalog.read_text())
    args.output.write_text(generate(data))
    args.output.with_name('online_font_names.h').write_text(generate_names(data))
