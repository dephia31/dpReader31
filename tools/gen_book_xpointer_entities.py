"""Generate the factual HTML4 entity-name/code-point table using Python's stdlib."""
from html.entities import name2codepoint
from pathlib import Path
entries={**name2codepoint,'apos':39}
out=['/* Generated by tools/gen_book_xpointer_entities.py; do not edit. */','/* HTML4 entity name/code-point facts, via Python html.entities. */','static const struct { const char *name; uint32_t cp; } xpointer_entities[] = {']
out += [f'    {{"{name}", {cp}u}},' for name,cp in sorted(entries.items())]
out += ['};','']
Path(__file__).resolve().parents[1].joinpath('main/book/book_xpointer_entities.h').write_text('\n'.join(out))
