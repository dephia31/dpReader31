"""Encode the supplied logo as a flash-resident 4bpp asset. Requires Pillow."""
import argparse
import hashlib
from pathlib import Path
from PIL import Image
ROOT = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--source', type=Path, default=ROOT/'main/assets/branding/dpreader-logo-source.png')
p.add_argument('--width', type=int, default=540)
args = p.parse_args()
if args.width <= 0 or args.width > 600 or args.width % 2:
    p.error('width must be even and between 2 and 600')
source = Image.open(args.source).convert('RGBA')
white = Image.new('RGBA', source.size, 'white')
white.alpha_composite(source)
gray = white.convert('L')
bounds = gray.point(lambda value: 255 if value < 224 else 0).getbbox()
if not bounds:
    raise ValueError('Logo has no visible ink')
left, top, right, bottom = bounds
gray = gray.crop((max(0,left-2), max(0,top-2), min(gray.width,right+2), min(gray.height,bottom+2)))
height = round(gray.height*args.width/gray.width)
gray = gray.resize((args.width,height), Image.Resampling.LANCZOS)
levels = [15 if value >= 248 else min(15,(value+8)//17) for value in gray.tobytes()]
packed = bytes((levels[i]<<4)|levels[i+1] for i in range(0,len(levels),2))
assert len(packed) == args.width*height//2
(ROOT/'main/assets/startup_logo_4bpp.bin').write_bytes(packed)
(ROOT/'main/assets/startup_logo.h').write_text(
    '/* Generated by tools/gen_startup_logo.py; do not edit by hand. */\n#pragma once\n'
    f'#define DPREADER_STARTUP_LOGO_WIDTH {args.width}\n'
    f'#define DPREADER_STARTUP_LOGO_HEIGHT {height}\n'
    f'/* Source SHA256: {hashlib.sha256(args.source.read_bytes()).hexdigest()} */\n')
print(f'Logo: {args.width}x{height}, {len(packed)} bytes, source crop={bounds}')
